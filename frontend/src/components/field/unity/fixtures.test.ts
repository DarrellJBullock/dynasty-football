/**
 * Shared fixtures for the Unity viewer (docs/design/depth-and-unity.md §4.1): timelines the
 * choreographer builds, with timeline.ts's samples of them. Unity's sampler is checked
 * against the same file (unity/Assets/Dynasty/Tests/EditMode/TimelineSamplerTests.cs), so
 * the two viewers can't drift apart.
 *
 * After changing the choreographer or the sampler, rewrite the file and check it in:
 *   UPDATE_UNITY_FIXTURES=1 npx vitest run src/components/field/unity/fixtures.test.ts
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import type { PlaybackPlay, PlayEvent } from "@/lib/types";
import { makePlay, makePlayback, opponent, pid, team } from "@/test/fixtures";
import { choreographGame } from "../playback/choreograph";
import { anglesAt, ballAt, facingAt, handsAt, positionAt, type PlayTimeline } from "../playback/timeline";
import { build as buildOf, hipHeight, type JointAngles } from "../players/poses";

const FILE = path.resolve(__dirname, "../../../../../unity/Assets/Dynasty/Tests/Fixtures/timelines.json");
const STEP = 0.25; // seconds between samples
const H = team.id;
const A = opponent.id;

const kick = (events: PlayEvent[], overrides: Partial<PlaybackPlay>) =>
  makePlay({ down: null, distance: null, ball_on: null, defense: null, personnel: null, events,
             result: { type: events[0].t }, ...overrides });

const PLAYS: Record<string, PlaybackPlay> = {
  run: makePlay({
    result: { type: "run", yards: 6 },
    events: [{ t: "handoff", to: pid(H, "RB"), direction: "inside" },
             { t: "rush", player: pid(H, "RB"), yards: 6 }, { t: "tackle", by: [pid(A, "MLB")] }],
  }),
  pass: makePlay({
    result: { type: "pass", yards: 14, result: "complete" },
    events: [{ t: "dropback", qb: pid(H, "QB"), depth: "short" },
             { t: "pass", qb: pid(H, "QB"), target: pid(H, "WR"), result: "complete", air: 8, yards: 14 },
             { t: "tackle", by: [pid(A, "CB")] }],
  }),
  punt: kick([{ t: "punt", punter: pid(H, "P"), yards: 45, touchback: false, fair_catch: false,
                return: 8, returner: pid(A, "WR") }], { down: 4, distance: 6, ball_on: 40 }),
};

const round = (n: number) => Math.round(n * 1e6) / 1e6;

/** JointAngles in a fixed order (Poses.cs JointAngles.ToArray). */
const ANGLES: (keyof JointAngles)[] = ["hipL", "hipR", "kneeL", "kneeR", "shoulderL", "shoulderR",
  "elbowL", "elbowR", "spreadL", "spreadR", "torso", "crouch", "lie"];

function samples(timeline: PlayTimeline) {
  const players = new Map(timeline.players.map((p) => [p.id, p]));
  const out = [];
  for (let t = 0; t <= timeline.duration + 1e-9; t += STEP) {
    out.push({
      t: round(t),
      // Per player, in timeline order: x, y, facing, the 13 joint angles (ANGLES), and how
      // high his hips sit.
      players: timeline.players.map((p) => {
        const { x, y } = positionAt(p.path, t);
        const angles = anglesAt(p, t);
        return [x, y, facingAt(p, t), ...ANGLES.map((k) => angles[k]),
                hipHeight(buildOf(p.heightIn, p.weightLb), angles)].map(round);
      }),
      ball: ballAt(timeline, t, (id, at) => handsAt(players.get(id)!, at)).map(round),
    });
  }
  return out;
}

function build() {
  const timelines = choreographGame(makePlayback(Object.values(PLAYS)));
  return {
    note: "Generated by frontend/src/components/field/unity/fixtures.test.ts; don't edit by hand.",
    step: STEP,
    cases: Object.keys(PLAYS).map((name, i) => ({
      name, timeline: timelines[i].timeline, samples: samples(timelines[i].timeline),
    })),
  };
}

describe("Unity fixtures", () => {
  it("match what the browser's sampler says (rewrite with UPDATE_UNITY_FIXTURES=1)", () => {
    const fixtures = JSON.parse(JSON.stringify(build())); // (as it reads back from the file)
    if (process.env.UPDATE_UNITY_FIXTURES) writeFileSync(FILE, `${JSON.stringify(fixtures)}\n`);
    expect(JSON.parse(readFileSync(FILE, "utf8"))).toEqual(fixtures);
  });
});
